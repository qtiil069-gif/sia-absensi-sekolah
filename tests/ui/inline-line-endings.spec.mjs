import { test, expect } from '@playwright/test';
import { createHash } from 'node:crypto';
import { escapeHtmlServiceScript } from '../../scripts/htmlservice-script.mjs';

const digest = (value) => createHash('sha256').update(value, 'utf8').digest('hex');
const unicode = 'Sekolah … é 漢字 ☀';
const quotes = 'Kutip: \' " ` dan $&';
const base64 = 'U2Vrb2xhaCDigKY=';

for (const [label, ending] of [['LF', '\n'], ['CRLF', '\r\n'], ['CR', '\r']]) {
  test(`inline ${label} input preserves exact generated bytes and runtime values through document.write`, async ({ page }) => {
    const source = [
      'window.__inlineProbe = {',
      '  template: `awal',
      'akhir`,',
      '  rawTemplate: String.raw`baris',
      'lain`,',
      String.raw`  escaped: '\r\n',`,
      "  continued: 'sa\\",
      "tu',",
      `  unicode: ${JSON.stringify(unicode)},`,
      `  quotes: ${JSON.stringify(quotes)},`,
      `  base64: ${JSON.stringify(base64)},`,
      '  xml: \'<?xml version="1.0"?>\',',
      "  comment: '<!-- aman -->'",
      '};'
    ].join(ending);
    const generated = escapeHtmlServiceScript(source);
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.evaluate((html) => {
      document.open(); document.write(html); document.close();
    }, `<script>${generated}</script>`);
    const rendered = await page.locator('script').textContent();
    // Compare the emitted source directly: no trimming, newline replacement,
    // or other normalization may hide corruption at the assertion boundary.
    expect(Buffer.byteLength(rendered, 'utf8')).toBe(Buffer.byteLength(generated, 'utf8'));
    expect(digest(rendered)).toBe(digest(generated));
    expect(rendered).toBe(generated);
    expect(await page.evaluate(() => window.__inlineProbe)).toEqual({
      template: 'awal\nakhir', rawTemplate: 'baris\nlain', escaped: '\r\n', continued: 'satu',
      unicode, quotes, base64, xml: '<?xml version="1.0"?>', comment: '<!-- aman -->'
    });
    expect(errors).toEqual([]);
  });
}
